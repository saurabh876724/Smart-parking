"""Write a JWT signing key for a development run (Phase 8).

    python scripts/dev_secret.py                  # create data/.secret
    python scripts/dev_secret.py --check          # is there a usable key already?
    python scripts/dev_secret.py --rotate --force # replace it (logs everyone out)

`configs/app.yaml` names where a key may live; it never holds one. This script is
the only writer of that file, and it writes 48 random bytes from `secrets` - the
CSPRNG - because a key generated by `random`, a timestamp, or a copy of a value
from a tutorial is a key that can be guessed or reproduced.

A production deployment sets the environment variable instead (`api.jwt_secret_env`,
`SMART_PARKING_JWT_SECRET` by default) and this file is never created: a key in a
file is fine on a laptop and bad in a repository, and the resolution order in
`core.config.jwt_secret_for` - environment first, file second - is what makes the
two setups differ by nothing but which one a machine has.

Rotating invalidates every token in circulation. That is the point of a rotation
and the reason it needs `--force` on top of `--rotate`: an accidental one takes the
operator's dashboard down mid-shift.
"""

from __future__ import annotations

import argparse
import os
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from smart_parking.core.config import SecretUnavailable, jwt_secret_for, load_config  # noqa: E402

# RFC 7518 says an HS256 key must be at least the hash's own 256 bits, so 32 bytes
# is the floor `jwt_secret_for` enforces. 48 is what gets generated: extra entropy
# costs nothing here and removes any argument about whether the floor was measured
# correctly on the machine writing the file.
KEY_BYTES = 48


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--check", action="store_true", help="report the key this machine would use, write nothing")
    ap.add_argument("--rotate", action="store_true", help="replace an existing key")
    ap.add_argument("--force", action="store_true", help="confirm --rotate")
    args = ap.parse_args()

    cfg = load_config(root=ROOT)
    path = cfg.resolve(cfg.api.jwt_secret_file)

    if args.check:
        try:
            secret = jwt_secret_for(cfg)
        except SecretUnavailable as exc:
            print(f"no usable key: {exc}")
            return 1
        origin = f"${cfg.api.jwt_secret_env}" if os.environ.get(cfg.api.jwt_secret_env) else path
        print(f"usable key: {len(secret.encode())} bytes from {origin}")
        return 0

    if path.exists() and not args.rotate:
        print(f"{path} already exists - leaving it alone.")
        print("Tokens already issued stay valid, which is what a restart should do.")
        print("Use --rotate --force to replace it and invalidate them.")
        return 0

    if args.rotate and not args.force:
        print("--rotate needs --force: every token this key signed becomes invalid.")
        return 1

    key = secrets.token_urlsafe(KEY_BYTES)
    path.parent.mkdir(parents=True, exist_ok=True)
    # 0o600 is a no-op on Windows without the right ACL, so it is attempted rather
    # than assumed - the file's contents are a key, and the effort is free.
    path.write_text(key + "\n", encoding="utf-8")
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass

    print(f"wrote {len(key.encode())} bytes to {path}")
    print("It is gitignored (data/.secret). Do not move it into configs/app.yaml.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
